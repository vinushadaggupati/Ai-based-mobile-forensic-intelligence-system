st.caption("Each finding is classified into Confirmed Evidence, AI Observation, or Possible Lead.")

if all_findings:
    f_table = []
    for f in all_findings:
        f_table.append({
            "Classification": f["verification_status"],
            "Severity": f["severity"],
            "Category": f["analysis_type"],
            "Finding Description": f["finding_description"],
            "Timestamp": f["timestamp"]
        })
    st.dataframe(pd.DataFrame(f_table), use_container_width=True, hide_index=True)
else:
    st.info("No specific anomalies detected yet. Upload evidence files above to perform deep analysis.")


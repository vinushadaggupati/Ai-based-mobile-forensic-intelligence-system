import streamlit as st
import pandas as pd
import json
import os
from datetime import datetime

from modules.ai_analyzer import generate_forensic_ai_summary, AI_MODEL_NAME
from modules.database import get_case, get_ai_reports_by_case, get_analysis_results_by_case, get_evidence_by_case
from modules.evidence_acquisition import register_uploaded_file
from modules.forensic_analyzer import run_full_case_analysis
from modules.report_generator import generate_pdf_report

st.set_page_config(page_title="AI Evidence Analyzer", page_icon="🤖", layout="wide")

case_id = st.session_state.get("active_case_id")
if not case_id:
    st.warning("⚠️ Please select or create an active investigation case first.")
    st.stop()

case_info = get_case(case_id) or {}
st.title("🤖 AI-Based Evidence Analyzer")
st.caption(f"Active Case: **{case_info.get('case_name')}** (`{case_id}`)")

# ─── MANDATORY FORENSIC AI DISCLAIMER (NIST SP 800-101) ──────────────────────
st.warning(
    "⚠️ **Forensic AI Admissibility Disclaimer (NIST SP 800-101 & ISO/IEC 27037):** "
    "All outputs generated by this module are categorized strictly into **Confirmed Evidence**, **AI Observation**, and **Possible Lead**. "
    "AI-generated predictions and pattern correlations serve as **investigative aids only** and must **never** be presented as confirmed courtroom facts "
    "without independent validation by a certified digital forensics examiner."
)

# ─── SECTION 1: AI INFERENCE ENGINE STATUS ────────────────────────────────────
st.subheader("1. AI Inference Engine Status")

col_ai1, col_ai2 = st.columns([3, 1])
with col_ai1:
    st.success(f"**Active Model:** {AI_MODEL_NAME}", icon="🟢")
    st.caption("Multi-Modal Android Intelligence Core · Air-Gapped Local Neural Engine · Zero External Daemon Dependencies")

with col_ai2:
    if st.button("🔄 Re-Run AI Analysis", use_container_width=True, type="primary"):
        with st.spinner("Synthesizing multi-modal forensic findings..."):
            generate_forensic_ai_summary(case_id=case_id)
            st.success("AI analysis updated!")
            st.rerun()

st.divider()

# ─── SECTION 2: EVIDENCE FILE UPLOAD & AUTOMATIC ANALYSIS ─────────────────────
st.subheader("2. Upload Android Forensic Evidence File")
st.caption("Upload an Android evidence package (.json, .csv, .log, .txt, .sqlite) to automatically extract, correlate, and analyze its contents.")

uploaded_file = st.file_uploader(
    "Choose Forensic Evidence File to Analyze:",
    type=["json", "csv", "log", "txt", "sqlite", "db", "xml"],
    key="ai_evidence_uploader"
)

if uploaded_file is not None:
    file_bytes = uploaded_file.getvalue()
    file_name = uploaded_file.name

    with st.spinner(f"Ingesting '{file_name}', computing SHA-256, and running AI correlation..."):
        # Register in SQLite
        ev_rec = register_uploaded_file(
            file_bytes=file_bytes,
            original_filename=file_name,
            case_id=case_id,
            acquisition_method="AI_DIRECT_UPLOAD"
        )
        # Automatically run forensic analysis rules on the file
        run_full_case_analysis(case_id)
        # Automatically run AI synthesis
        ai_res = generate_forensic_ai_summary(case_id=case_id)

    st.success(f"✅ Ingested **{file_name}** ({len(file_bytes)} bytes) · SHA-256: `{ev_rec['sha256_hash'][:16]}...`")
    st.info("⚡ Automatic AI analysis completed on uploaded evidence file!")

# ─── SECTION 3: AI ANALYSIS RESULTS & ARTIFACT CORRELATIONS ───────────────────
saved_reports = get_ai_reports_by_case(case_id)
if not saved_reports:
    # Auto-generate if not yet generated
    with st.spinner("Generating initial AI multi-modal correlation for this case..."):
        generate_forensic_ai_summary(case_id=case_id)
        saved_reports = get_ai_reports_by_case(case_id)

latest_report = saved_reports[0] if saved_reports else None
all_findings = get_analysis_results_by_case(case_id)
all_evidence = get_evidence_by_case(case_id)

# PDF Generation Button (Prominent)
st.subheader("3. Forensic Investigation Report Deliverable")
pdf_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "generated_reports", case_id, f"Forensic_Investigation_Report_{case_id}.pdf")

if not os.path.exists(pdf_path):
    generate_pdf_report(case_id)

if os.path.exists(pdf_path):
    with open(pdf_path, "rb") as f:
        pdf_bytes = f.read()
    st.download_button(
        label="📥 Download Official 20-Section Forensic PDF Report",
        data=pdf_bytes,
        file_name=f"Forensic_Report_{case_id}.pdf",
        mime="application/pdf",
        type="primary",
        use_container_width=True
    )

st.divider()

# ─── SECTION 4: AI INVESTIGATION SUMMARY NARRATIVE ────────────────────────────
st.subheader("4. AI-Based Investigation Summary Narrative")
if latest_report:
    st.caption(f"Synthesized on {latest_report['generation_timestamp']} via {latest_report['ollama_model_name']}")
    st.markdown(f"""
    <div style="background-color: #0f172a; border-left: 4px solid #0284c7; padding: 18px; border-radius: 6px; font-family: monospace; font-size: 13px; line-height: 1.6; white-space: pre-wrap; color: #f8fafc;">
{latest_report['ai_summary']}
    </div>
    """, unsafe_allow_html=True)

